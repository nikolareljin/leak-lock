/**
 * Scan engine configuration and command construction.
 *
 * Single source of truth for how detection engines are invoked. Deliberately has no
 * `vscode` import (same rule as git-rewrite.js) so every argument list can be asserted
 * in unit tests without a VS Code host — the flags in here decide whether findings are
 * reported or silently discarded, so they need to be directly testable.
 */

// Nosey Parker upstream (praetorian-inc/noseyparker) was archived read-only on
// 2026-04-24. v0.24.0 (2025-05-08) is its final release, so this tag can never move.
// Pinning it replaces the previous `:latest`, which silently drifted between machines.
const NOSEYPARKER_IMAGE_REPO = 'ghcr.io/praetorian-inc/noseyparker';
const NOSEYPARKER_PINNED_VERSION = 'v0.24.0';
const NOSEYPARKER_IMAGE = `${NOSEYPARKER_IMAGE_REPO}:${NOSEYPARKER_PINNED_VERSION}`;
// Expected manifest digest for the pinned tag. Used to warn on drift; not used as the
// pull reference, because an opaque digest makes every error message unreadable.
const NOSEYPARKER_EXPECTED_DIGEST =
    'sha256:956b795de95c9ddd95e0024e7c893e048cc50e9442e9328025e5dd1afedaf08e';
const NOSEYPARKER_ARCHIVED_NOTICE =
    'Nosey Parker upstream was archived on 2026-04-24; its ruleset is frozen at v0.24.0.';

// `report` defaults that discard data. Nosey Parker caps matches per finding at 3,
// provenance entries per match at 3, and drops findings scoring below 0.05 — none of
// which was overridden, so the results table showed at most three matches per rule
// group no matter how many existed. -1 and 0 are the documented "no limit" values.
const REPORT_NO_LIMIT = '-1';
const REPORT_NO_MIN_SCORE = '0';

const DEFAULT_SCAN_TIMEOUT_MS = 600000; // 10 minutes
const DEFAULT_MAX_FILE_SIZE_MB = 100; // matches Nosey Parker's own default

/**
 * Ruleset selection.
 *
 * Nosey Parker's `--ruleset` defaults to `default`, which since v0.16.0 covers secret
 * detection only — cloud assets and identifiers live in a separate `np.assets` ruleset
 * that was never loaded. Passing the option at all disables the default ruleset, so
 * adding to it requires repeating the option.
 */
const RULESET_MODES = Object.freeze({
    default: ['default'],
    'default+assets': ['default', 'np.assets'],
    all: ['all']
});

function resolveRulesetIds(mode) {
    return RULESET_MODES[mode] || RULESET_MODES.default;
}

/**
 * Normalise raw VS Code settings into the shape the builders expect.
 * Every value is clamped here so callers cannot pass something the engine will reject.
 */
function normalizeScanSettings(raw = {}) {
    const timeoutSeconds = clampNumber(raw.timeoutSeconds, 30, 7200, DEFAULT_SCAN_TIMEOUT_MS / 1000);
    const maxFileSizeMb = clampNumber(raw.maxFileSizeMb, 0, 100000, DEFAULT_MAX_FILE_SIZE_MB);
    return {
        image: typeof raw.image === 'string' && raw.image.trim() ? raw.image.trim() : NOSEYPARKER_IMAGE,
        rulesetMode: Object.prototype.hasOwnProperty.call(RULESET_MODES, raw.rulesetMode)
            ? raw.rulesetMode
            : 'default',
        suppressRedundant: raw.suppressRedundant !== false,
        maxFileSizeMb,
        refreshRefsBeforeScan: raw.refreshRefsBeforeScan !== false,
        timeoutMs: timeoutSeconds * 1000
    };
}

function clampNumber(value, min, max, fallback) {
    const n = Number(value);
    if (!Number.isFinite(n)) {
        return fallback;
    }
    return Math.min(max, Math.max(min, n));
}

/**
 * Directories that are unambiguously third-party and safe to exclude from scanning
 * entirely when the user selects `dependencyHandling: "exclude"`.
 *
 * Deliberately much narrower than the list used to *classify* a finding as a
 * dependency. Classification errs toward flagging (`lib/`, `bin/`, `dist/`, `build/`,
 * `out/`, `packages/` are all in that list) because a misclassified finding is still
 * shown. Exclusion errs toward scanning: those same directories routinely hold
 * first-party source, and skipping them would hide real secrets. A security scanner
 * that silently stops looking at `lib/` is worse than one that mislabels it.
 */
const EXCLUDABLE_DEPENDENCY_DIRS = Object.freeze([
    'node_modules',
    'vendor',
    'site-packages',
    '__pycache__',
    '.venv',
    'venv',
    '.npm',
    'npm-cache',
    '.m2',
    '.gradle',
    '.cargo',
    '.bundle',
    'gems',
    'Pods',
    'nuget'
]);

/**
 * gitignore-syntax content for Nosey Parker's `--ignore` option.
 * Anchored to any depth so a nested `node_modules` is covered too.
 */
function buildDependencyIgnoreFile(dirs = EXCLUDABLE_DEPENDENCY_DIRS) {
    const header = [
        '# Generated by Leak Lock for dependencyHandling="exclude".',
        '# Only unambiguously third-party directories are listed: excluding a directory',
        '# that may hold first-party source would hide real secrets.',
        ''
    ];
    return header.concat(dirs.map(dir => `${dir}/`)).join('\n') + '\n';
}

/**
 * Is this path inside a directory the user asked to exclude?
 *
 * Only Nosey Parker takes an ignore file, so applying `dependencyHandling: "exclude"`
 * to its command alone made the setting mean different things per engine — Gitleaks and
 * TruffleHog kept reporting `node_modules`. This predicate applies the same rule to
 * every engine's output, so the setting behaves identically whichever engines are on.
 */
function isInExcludedDependencyDir(filePath, dirs = EXCLUDABLE_DEPENDENCY_DIRS) {
    if (typeof filePath !== 'string' || !filePath) {
        return false;
    }
    const normalised = filePath.replace(/\\/g, '/');
    return dirs.some(dir =>
        normalised === dir
        || normalised.startsWith(`${dir}/`)
        || normalised.includes(`/${dir}/`)
    );
}

/**
 * Build the `docker run … noseyparker scan` argument list.
 *
 * @param {object} options
 * @param {string} options.scanMount host path mounted at /scan
 * @param {string} options.datastoreMount host path mounted at /datastore
 * @param {string} [options.ignoreFileMount] host path of a gitignore-syntax exclude file
 * @param {object} [options.settings] output of normalizeScanSettings()
 */
function buildNoseyParkerScanArgs({ scanMount, datastoreMount, ignoreFileMount, settings } = {}) {
    const cfg = settings || normalizeScanSettings();
    const args = [
        'run', '--rm',
        // Read-only: scanning never needs to write to the audited tree, and the
        // datastore has its own writable mount. Without :ro the container could write
        // into the user's repository, which is exactly what moving the datastore out
        // of the scan root was meant to stop.
        '-v', `${scanMount}:/scan:ro`,
        '-v', `${datastoreMount}:/datastore`
    ];

    if (ignoreFileMount) {
        args.push('-v', `${ignoreFileMount}:/leaklock-ignore:ro`);
    }

    args.push(
        cfg.image,
        'scan',
        '--datastore', '/datastore',
        '--git-history', 'full'
    );

    for (const ruleset of resolveRulesetIds(cfg.rulesetMode)) {
        args.push('--ruleset', ruleset);
    }

    // A non-positive value means "no limit" upstream, so 0 disables the cap entirely.
    args.push('--max-file-size', String(cfg.maxFileSizeMb));

    if (ignoreFileMount) {
        args.push('--ignore', '/leaklock-ignore');
    }

    args.push('/scan');
    return args;
}

/**
 * Build the `docker run … noseyparker report` argument list.
 *
 * The three no-limit flags are the fix for findings being discarded before Leak Lock
 * ever parsed them. Do not reintroduce the defaults without also telling the user that
 * results were truncated.
 */
function buildNoseyParkerReportArgs({ datastoreMount, settings } = {}) {
    const cfg = settings || normalizeScanSettings();
    return [
        'run', '--rm',
        '-v', `${datastoreMount}:/datastore`,
        cfg.image,
        'report',
        '--datastore', '/datastore',
        '--format', 'json',
        '--max-matches', REPORT_NO_LIMIT,
        '--max-provenance', REPORT_NO_LIMIT,
        '--min-score', REPORT_NO_MIN_SCORE,
        '--suppress-redundant', cfg.suppressRedundant ? 'true' : 'false'
    ];
}

/**
 * Build the `docker run … noseyparker datastore init` argument list.
 */
function buildNoseyParkerDatastoreInitArgs({ parentMount, datastoreName, settings } = {}) {
    const cfg = settings || normalizeScanSettings();
    return [
        'run', '--rm',
        '-v', `${parentMount}:/workspace`,
        cfg.image,
        'datastore', 'init',
        '--datastore', `/workspace/${datastoreName}`
    ];
}

/**
 * Build the `docker run … noseyparker --version` argument list.
 * The resolved version is recorded on every finding so a result set can be reproduced.
 */
function buildNoseyParkerVersionArgs({ settings } = {}) {
    const cfg = settings || normalizeScanSettings();
    return ['run', '--rm', cfg.image, '--version'];
}

module.exports = {
    NOSEYPARKER_IMAGE_REPO,
    NOSEYPARKER_PINNED_VERSION,
    NOSEYPARKER_IMAGE,
    NOSEYPARKER_EXPECTED_DIGEST,
    NOSEYPARKER_ARCHIVED_NOTICE,
    DEFAULT_SCAN_TIMEOUT_MS,
    DEFAULT_MAX_FILE_SIZE_MB,
    RULESET_MODES,
    EXCLUDABLE_DEPENDENCY_DIRS,
    buildDependencyIgnoreFile,
    isInExcludedDependencyDir,
    resolveRulesetIds,
    normalizeScanSettings,
    buildNoseyParkerScanArgs,
    buildNoseyParkerReportArgs,
    buildNoseyParkerDatastoreInitArgs,
    buildNoseyParkerVersionArgs
};
